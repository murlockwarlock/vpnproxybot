def fmt_user(user_id: int, username: Optional[str], first_name: str = "") -> str:
    """Return a clickable Telegram user link for HTML parse mode."""
    if username:
        label = f"{first_name} (@{username})" if first_name else f"@{username}"
        return f'<a href="https://t.me/{username}">{label}</a>'
    label = first_name or f"ID:{user_id}"
    return f'<a href="tg://user?id={user_id}">{label}</a>'


